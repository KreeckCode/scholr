"""
LMS Bridge models.

LearnerLMSAccount is the single bridge between academics.Learner and accounts.User.
It only exists when a school learner is given online access. It is opt-in — most
learners will never have one. The bridge is one-to-one in both directions.

OnlineEnrollment (added in Stage 12B) tracks which online courses a learner is
enrolled in via the academic system, separate from commercial shop enrollments.
"""

import unicodedata
import re

from django.conf import settings
from django.db import models

from .learner import Learner
from .school import AcademicYear


class LearnerLMSAccount(models.Model):
    """
    Bridge between academics.Learner and accounts.User (role=STUDENT).

    One record per learner who has been granted online access. Creating this
    record also creates the User account and queues the Moodle user sync.

    The temporary password is NEVER stored here — it is generated by
    LMSBridgeService, shown once on the credentials screen, and discarded.
    """

    learner = models.OneToOneField(
        Learner,
        on_delete=models.CASCADE,
        related_name='lms_account',
    )
    user = models.OneToOneField(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name='learner_lms_account',
        help_text='The accounts.User created for this learner (role=STUDENT)',
    )

    is_active = models.BooleanField(
        default=True,
        db_index=True,
        help_text='Inactive accounts are suspended in Moodle and cannot log in',
    )

    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        related_name='lms_accounts_created',
    )
    created_at = models.DateTimeField(auto_now_add=True)

    deactivated_at = models.DateTimeField(null=True, blank=True)
    deactivated_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='lms_accounts_deactivated',
    )

    notes = models.TextField(
        blank=True,
        help_text="Why this account was created (e.g., 'Extra Maths support, Term 2')",
    )

    class Meta:
        db_table = 'learner_lms_accounts'
        verbose_name = 'Learner LMS Account'
        verbose_name_plural = 'Learner LMS Accounts'
        ordering = ['-created_at']

    def __str__(self):
        return (
            f"{self.learner.get_full_name()} → "
            f"{self.user.username} "
            f"({'active' if self.is_active else 'inactive'})"
        )

    def moodle_sync_status(self) -> str:
        """Return Moodle sync status from MoodleUserMapping if it exists."""
        try:
            return self.user.moodle_mapping.sync_status
        except Exception:
            return 'not_mapped'

    def is_synced_to_moodle(self) -> bool:
        """True when the Moodle user ID is set and sync is complete."""
        try:
            return bool(
                self.user.moodle_mapping.moodle_user_id
                and self.user.moodle_mapping.sync_status == 'synced'
            )
        except Exception:
            return False

    def moodle_user_id(self):
        """Return the Moodle user ID or None."""
        try:
            return self.user.moodle_mapping.moodle_user_id
        except Exception:
            return None
        

class OnlineEnrollment(models.Model):
    """
    Academic-side tracking record for a school learner enrolled in an online course.

    This is NOT integration.CourseEnrollment — that is the Moodle sync record.
    OnlineEnrollment is the academic decision: who enrolled whom, why, and in
    support of which school subject or intervention.

    One record per learner+course+academic_year. Re-enrollment after withdrawal
    updates the existing record (update_or_create) rather than creating a new one.
    Progress is cached here from CourseEnrollment to avoid cross-app joins.
    """

    STATUS_PENDING = 'pending'       # LMS account or course not yet in Moodle
    STATUS_ACTIVE = 'active'         # Enrolled and confirmed in Moodle
    STATUS_WITHDRAWN = 'withdrawn'   # Unenrolled from Moodle
    STATUS_COMPLETED = 'completed'   # Learner finished the course

    STATUS_CHOICES = [
        (STATUS_PENDING, 'Pending Moodle Sync'),
        (STATUS_ACTIVE, 'Active'),
        (STATUS_WITHDRAWN, 'Withdrawn'),
        (STATUS_COMPLETED, 'Completed'),
    ]

    learner = models.ForeignKey(
        Learner,
        on_delete=models.CASCADE,
        related_name='online_enrollments',
    )
    # String reference avoids circular imports between lms_link and integration
    course = models.ForeignKey(
        'integration.Course',
        on_delete=models.PROTECT,
        related_name='academic_enrollments',
    )
    academic_year = models.ForeignKey(
        AcademicYear,
        on_delete=models.PROTECT,
        related_name='online_enrollments',
    )

    # Link to the actual Moodle sync record in the integration app
    course_enrollment = models.OneToOneField(
        'integration.CourseEnrollment',
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='academic_enrollment',
    )

    # Academic context — why was this enrollment created
    intervention = models.ForeignKey(
        'academics.LearnerIntervention',
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='online_enrollments',
        help_text='Intervention that prompted this enrollment, if any',
    )
    subject = models.ForeignKey(
        'academics.SchoolSubject',
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='online_enrollments',
        help_text='School subject this online course is supporting',
    )

    status = models.CharField(
        max_length=20,
        choices=STATUS_CHOICES,
        default=STATUS_PENDING,
        db_index=True,
    )
    enrollment_reason = models.TextField(
        blank=True,
        help_text='Why this online enrollment was created',
    )
    admin_notes = models.TextField(blank=True)

    enrolled_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        related_name='online_enrollments_created',
    )
    enrolled_at = models.DateTimeField(auto_now_add=True)

    withdrawn_at = models.DateTimeField(null=True, blank=True)
    withdrawn_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='online_enrollments_withdrawn',
    )

    # Cached from integration.CourseEnrollment — updated by sync_progress_for_learner
    progress_percentage = models.DecimalField(
        max_digits=5,
        decimal_places=2,
        default=0,
        help_text='Cached from Moodle via CourseEnrollment.progress_percentage',
    )
    progress_last_synced = models.DateTimeField(
        null=True,
        blank=True,
    )

    class Meta:
        db_table = 'online_enrollments'
        verbose_name = 'Online Enrollment'
        verbose_name_plural = 'Online Enrollments'
        unique_together = [['learner', 'course', 'academic_year']]
        ordering = ['-enrolled_at']
        indexes = [
            models.Index(
                fields=['learner', 'status'],
                name='idx_oe_learner_status',
            ),
            models.Index(
                fields=['academic_year', 'status'],
                name='idx_oe_year_status',
            ),
        ]

    def __str__(self):
        return (
            f"{self.learner.get_full_name()} → "
            f"{self.course.short_name} ({self.status})"
        )

    def is_active(self):
        return self.status == self.STATUS_ACTIVE

    def progress_display(self):
        """Progress as a rounded integer for template use."""
        return int(self.progress_percentage)
    

class OnlineProgressAlert(models.Model):
    """
    Audit record for every stall notification sent to staff.
    The sent_at timestamp enforces a cooldown window so the same
    learner+course pair isn't alerted more than once per period.
    """

    ALERT_STALL       = 'stall'
    ALERT_NOT_STARTED = 'not_started'
    ALERT_TYPES = [
        (ALERT_STALL,       'Progress Stalled'),
        (ALERT_NOT_STARTED, 'Not Started'),
    ]

    learner = models.ForeignKey(
        'academics.Learner',
        on_delete=models.CASCADE,
        related_name='progress_alerts',
    )
    course = models.ForeignKey(
        'integration.Course',
        on_delete=models.CASCADE,
        related_name='progress_alerts',
    )
    alert_type = models.CharField(max_length=20, choices=ALERT_TYPES)
    sent_at = models.DateTimeField(auto_now_add=True)
    days_stalled = models.PositiveIntegerField(default=0)
    # Snapshot of progress at the moment the alert fired
    progress_at_send = models.DecimalField(
        max_digits=5, decimal_places=2, null=True, blank=True,
    )
    # Comma-separated list of addresses the alert was dispatched to
    sent_to_emails = models.TextField(blank=True)

    class Meta:
        ordering = ['-sent_at']
        indexes = [
            models.Index(fields=['learner', 'course', 'sent_at']),
        ]

    def __str__(self):
        return (
            f'{self.learner} / {self.course} '
            f'({self.get_alert_type_display()}) '
            f'{self.sent_at.date()}'
        )