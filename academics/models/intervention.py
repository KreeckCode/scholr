from django.conf import settings
from django.db import models

from .learner import Learner
from .school import AcademicYear
from .curriculum import SubjectOffering


class PerformanceAnalysis(models.Model):
    """
    Cached snapshot of a learner's academic risk for an academic year.
    Generated by PerformanceAnalyzerService and read by dashboards.
    One record per learner per year - update_or_create on each run.
    """

    RISK_LOW = "low"
    RISK_MEDIUM = "medium"
    RISK_HIGH = "high"
    RISK_CRITICAL = "critical"

    RISK_CHOICES = [
        (RISK_LOW, "Low Risk"),
        (RISK_MEDIUM, "Medium Risk"),
        (RISK_HIGH, "High Risk"),
        (RISK_CRITICAL, "Critical"),
    ]

    TREND_IMPROVING = "improving"
    TREND_STABLE = "stable"
    TREND_DECLINING = "declining"
    TREND_UNKNOWN = "unknown"

    TREND_CHOICES = [
        (TREND_IMPROVING, "Improving"),
        (TREND_STABLE, "Stable"),
        (TREND_DECLINING, "Declining"),
        (TREND_UNKNOWN, "Insufficient data"),
    ]

    learner = models.ForeignKey(
        Learner,
        on_delete=models.CASCADE,
        related_name="performance_analyses",
    )
    academic_year = models.ForeignKey(
        AcademicYear,
        on_delete=models.CASCADE,
        related_name="performance_analyses",
    )

    risk_level = models.CharField(
        max_length=20,
        choices=RISK_CHOICES,
        default=RISK_LOW,
        db_index=True,
    )
    risk_score = models.IntegerField(
        default=0,
        help_text="Cumulative score from risk factors. Higher = more at risk.",
    )

    # Risk flags stored as a JSON list of structured dicts:
    # [{"type": "FAILING_SUBJECT", "subject": "Mathematics", "percentage": 35.5}, ...]
    risk_flags = models.JSONField(
        default=list,
        help_text="Structured list of risk factors identified during analysis",
    )

    # Subject-level summary counts
    subjects_total = models.IntegerField(default=0)
    subjects_passing = models.IntegerField(default=0)
    subjects_failing = models.IntegerField(default=0)
    subjects_incomplete = models.IntegerField(default=0)

    # Overall performance
    average_percentage = models.DecimalField(
        max_digits=5,
        decimal_places=2,
        null=True,
        blank=True,
    )
    trend = models.CharField(
        max_length=20,
        choices=TREND_CHOICES,
        default=TREND_UNKNOWN,
    )

    # Audit
    analysed_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="analyses_run",
        help_text="Null = automatic analysis",
    )
    analysed_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = "performance_analyses"
        verbose_name = "Performance Analysis"
        verbose_name_plural = "Performance Analyses"
        unique_together = [["learner", "academic_year"]]
        ordering = ["-risk_score", "learner__last_name"]
        indexes = [
            models.Index(
                fields=["academic_year", "risk_level"],
                name="idx_analysis_year_risk",
            ),
            models.Index(fields=["risk_score"], name="idx_analysis_score"),
        ]

    def __str__(self):
        return (
            f"{self.learner.get_full_name()} - "
            f"{self.get_risk_level_display()} ({self.academic_year.year})"
        )

    def is_at_risk(self):
        return self.risk_level != self.RISK_LOW

    def get_flags_display(self):
        """Return flags with human-readable labels for template rendering."""
        labels = {
            "FAILING_SUBJECT": "Failing subject",
            "FAILING_MULTIPLE": "Failing multiple subjects",
            "DOWNWARD_TREND": "Declining performance",
            "BELOW_PASS_CURRENT_TERM": "Below pass mark this term",
            "NO_MARKS_CAPTURED": "No marks on record",
        }
        return [
            {**flag, "label": labels.get(flag.get("type", ""), flag.get("type", ""))}
            for flag in (self.risk_flags or [])
        ]

    def risk_colour(self):
        """Tailwind colour key for the risk level - used in templates."""
        return {
            self.RISK_LOW: "green",
            self.RISK_MEDIUM: "yellow",
            self.RISK_HIGH: "orange",
            self.RISK_CRITICAL: "red",
        }.get(self.risk_level, "gray")


class InterventionProgram(models.Model):
    """
    Types of support programs available at this school.
    Seeded with common types via management command.
    Admins can add school-specific programs via the admin.
    """

    TYPE_EXTRA_CLASSES = "extra_classes"
    TYPE_PEER_TUTORING = "peer_tutoring"
    TYPE_SUBJECT_SUPPORT = "subject_support"
    TYPE_SOCIAL_WORKER = "social_worker"
    TYPE_PARENT_MEETING = "parent_meeting"
    TYPE_LSEN_REFERRAL = "lsen_referral"
    TYPE_COUNSELLING = "counselling"
    TYPE_READING_SUPPORT = "reading_support"
    TYPE_OTHER = "other"

    TYPE_CHOICES = [
        (TYPE_EXTRA_CLASSES, "Extra Classes"),
        (TYPE_PEER_TUTORING, "Peer Tutoring"),
        (TYPE_SUBJECT_SUPPORT, "Subject Support"),
        (TYPE_SOCIAL_WORKER, "Social Worker Referral"),
        (TYPE_PARENT_MEETING, "Parent Meeting"),
        (TYPE_LSEN_REFERRAL, "LSEN Assessment Referral"),
        (TYPE_COUNSELLING, "Counselling"),
        (TYPE_READING_SUPPORT, "Reading Support"),
        (TYPE_OTHER, "Other"),
    ]

    name = models.CharField(max_length=150, unique=True)
    program_type = models.CharField(max_length=30, choices=TYPE_CHOICES)
    description = models.TextField(blank=True)
    is_active = models.BooleanField(default=True, db_index=True)
    sort_order = models.IntegerField(default=0)

    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "intervention_programs"
        verbose_name = "Intervention Program"
        verbose_name_plural = "Intervention Programs"
        ordering = ["sort_order", "name"]

    def __str__(self):
        return self.name


class LearnerIntervention(models.Model):
    """
    An active or completed intervention for a specific learner.
    Can be subject-specific or general.
    Assigned to a staff member who is responsible for tracking.
    """

    STATUS_ACTIVE = "active"
    STATUS_COMPLETED = "completed"
    STATUS_CANCELLED = "cancelled"

    STATUS_CHOICES = [
        (STATUS_ACTIVE, "Active"),
        (STATUS_COMPLETED, "Completed"),
        (STATUS_CANCELLED, "Cancelled"),
    ]

    learner = models.ForeignKey(
        Learner,
        on_delete=models.CASCADE,
        related_name="interventions",
    )
    program = models.ForeignKey(
        InterventionProgram,
        on_delete=models.PROTECT,
        related_name="interventions",
    )
    academic_year = models.ForeignKey(
        AcademicYear,
        on_delete=models.CASCADE,
        related_name="interventions",
    )

    # Optional subject focus - null means school-wide/general intervention
    subject_offering = models.ForeignKey(
        SubjectOffering,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="interventions",
        help_text="Leave blank for general interventions not tied to a specific subject",
    )

    status = models.CharField(
        max_length=20,
        choices=STATUS_CHOICES,
        default=STATUS_ACTIVE,
        db_index=True,
    )
    start_date = models.DateField()
    end_date = models.DateField(
        null=True,
        blank=True,
        help_text="Leave blank for ongoing interventions",
    )

    assigned_to = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        related_name="assigned_interventions",
        limit_choices_to={"role__in": ["teacher", "hod", "principal", "admin"]},
        help_text="Staff member responsible for this intervention",
    )

    notes = models.TextField(
        blank=True,
        help_text="Reason for intervention and initial plan",
    )
    outcome_notes = models.TextField(
        blank=True,
        help_text="Outcome and effectiveness - filled in on completion",
    )

    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        related_name="interventions_created",
    )
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = "learner_interventions"
        verbose_name = "Learner Intervention"
        verbose_name_plural = "Learner Interventions"
        ordering = ["-created_at"]
        indexes = [
            models.Index(
                fields=["learner", "status"],
                name="idx_interv_learner_status",
            ),
            models.Index(
                fields=["academic_year", "status"],
                name="idx_interv_year_status",
            ),
        ]

    def __str__(self):
        return (
            f"{self.learner.get_full_name()} - "
            f"{self.program.name} ({self.get_status_display()})"
        )

    def is_active(self):
        return self.status == self.STATUS_ACTIVE


class ProgressNote(models.Model):
    """
    Teacher or HOD observation note on a learner's progress.
    General or subject-specific. Visible to all staff.
    Flagged notes can be shared with parents via the parent portal (Stage 10).
    """

    learner = models.ForeignKey(
        Learner,
        on_delete=models.CASCADE,
        related_name="progress_notes",
    )
    academic_year = models.ForeignKey(
        AcademicYear,
        on_delete=models.CASCADE,
        related_name="progress_notes",
    )

    # Optional subject context
    subject_offering = models.ForeignKey(
        SubjectOffering,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="progress_notes",
    )

    note = models.TextField()
    share_with_parent = models.BooleanField(
        default=False,
        help_text="When True, visible to parent on the parent portal",
    )

    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        related_name="progress_notes_written",
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "progress_notes"
        verbose_name = "Progress Note"
        verbose_name_plural = "Progress Notes"
        ordering = ["-created_at"]
        indexes = [
            models.Index(
                fields=["learner", "academic_year"],
                name="idx_note_learner_year",
            ),
        ]

    def __str__(self):
        subject = (
            f" ({self.subject_offering.subject.code})"
            if self.subject_offering
            else ""
        )
        return (
            f"{self.learner.get_full_name()}{subject} - "
            f"{self.created_at.strftime('%d %b %Y')}"
        )