"""
Write scholr/i18n_catalogue.py: every label, help text, choice and status name that the portals'
forms and pages can show from Python, so makemessages offers them to translators.

Run it whenever a model or form in the portals changes, then makemessages and compilemessages.
A test fails while the file is out of date, so nothing new slips through untranslated.
"""
import inspect
from pathlib import Path

from django import forms
from django.apps import apps
from django.conf import settings
from django.core.management.base import BaseCommand
from django.forms.utils import pretty_name

# What the portals show: every partner model, and the profile participants and coordinators edit
MODELS = ('partners.*', 'accounts.UserProfile', 'accounts.User')
FORM_MODULES = ('partners.forms',)
FORMS = ('accounts.forms.UserProfileForm', 'accounts.forms.UserUpdateForm', 'accounts.forms.ProfileCompletionForm')
OUTPUT = Path(settings.BASE_DIR) / 'scholr' / 'i18n_catalogue.py'


def _add(found, value):
    text = str(value or '').strip()
    if text and any(character.isalpha() for character in text):
        found.add(text)


def _choices(found, choices):
    choices = list(choices or ())
    # Long lists are countries and languages, named as people know them, not interface text
    if len(choices) > 60:
        return
    for _value, label in choices:
        if isinstance(label, (list, tuple)):
            _choices(found, label)
        else:
            _add(found, label)


def collect():
    # Always the English originals, whatever language happens to be active
    from django.utils import translation
    with translation.override(None):
        return _collect()


def _collect():
    found = set()
    for model in _models():
        for field in model._meta.get_fields():
            if getattr(field, 'auto_created', False) and not getattr(field, 'concrete', False):
                continue
            _choices(found, getattr(field, 'choices', None))
    for form_class in _forms():
        for field_name, field in form_class.base_fields.items():
            _add(found, field.label if field.label is not None else pretty_name(field_name))
            _add(found, field.help_text)
            if isinstance(field, forms.ChoiceField) and not isinstance(field, forms.ModelChoiceField):
                _choices(found, field.choices)
    return sorted(found)


def _models():
    for name in MODELS:
        app_label, model_name = name.split('.')
        if model_name == '*':
            yield from apps.get_app_config(app_label).get_models()
        else:
            yield apps.get_model(app_label, model_name)


def _forms():
    for module_name in FORM_MODULES:
        module = __import__(module_name, fromlist=['*'])
        for _name, form_class in inspect.getmembers(module, inspect.isclass):
            if issubclass(form_class, forms.BaseForm) and hasattr(form_class, 'base_fields'):
                yield form_class
    for path in FORMS:
        module_name, class_name = path.rsplit('.', 1)
        yield getattr(__import__(module_name, fromlist=[class_name]), class_name)


def render(strings):
    lines = [
        '"""Generated by manage.py build_i18n_catalogue for translators. Do not edit by hand."""',
        'from django.utils.translation import gettext_noop',
        '',
        'STRINGS = [',
    ]
    lines += [f'    gettext_noop({text!r}),' for text in strings]
    lines += [']', '']
    return '\n'.join(lines)


class Command(BaseCommand):
    help = 'List the labels, choices and status names the portals show from Python, for translators.'

    def handle(self, *args, **options):
        strings = collect()
        OUTPUT.write_text(render(strings), encoding='utf-8')
        self.stdout.write(f'Wrote {len(strings)} strings to {OUTPUT.relative_to(settings.BASE_DIR)}')
